#[must_use]
pub fn common(index: u8) -> [f32; 4] {
	to_float(COMMON_COLORS[usize::from(index)])
}

#[must_use]
pub fn hair(index: u8, mode: ColorMode) -> [f32; 4] {
	match mode {
		ColorMode::Common => common(index),
		ColorMode::Ver3 => VER3_HAIR_COLORS[usize::from(index)],
	}
}

#[must_use]
pub fn eye(index: u8, mode: ColorMode) -> [f32; 4] {
	match mode {
		ColorMode::Common => common(index),
		ColorMode::Ver3 => VER3_EYE_COLORS[usize::from(index)],
	}
}

#[must_use]
pub fn glass(index: u8, mode: ColorMode) -> [f32; 4] {
	match mode {
		ColorMode::Common => common(index),
		ColorMode::Ver3 => VER3_GLASS_COLORS[usize::from(index)],
	}
}

#[must_use]
pub fn mouth(index: u8, mode: ColorMode) -> [f32; 4] {
	match mode {
		ColorMode::Common => common(index),
		ColorMode::Ver3 => VER3_MOUTH_COLORS[usize::from(index)],
	}
}

#[must_use]
pub fn upper_lip(index: u8, mode: ColorMode) -> [f32; 4] {
	match mode {
		ColorMode::Common => to_float(UPPER_LIP_COLORS[usize::from(index)]),
		ColorMode::Ver3 => VER3_UPPER_LIP_COLORS[usize::from(index)],
	}
}

#[must_use]
pub fn faceline(index: u8) -> [f32; 4] {
	to_float(FACELINE_COLORS[usize::from(index)])
}

